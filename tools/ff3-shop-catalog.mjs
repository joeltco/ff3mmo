#!/usr/bin/env node
// ff3-shop-catalog.mjs — render every FF3 shop to docs/FF3-SHOPS.md.
//
// Pure ROM read through `lib/ff3-shops.mjs`. Verification is
// `ff3-shop-probe.mjs --all`, which opens all 21 and compares.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const { glyph } = await import('./lib/ff3-text.mjs');
const S = await import('./lib/ff3-shops.mjs');

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF3-SHOPS.md');
const ROMP = process.env.FF3_ROM || new URL('../FF3-English.nes', import.meta.url).pathname;
const rom = new Uint8Array(fs.readFileSync(ROMP));

const L = [];
L.push('# FF3 shops — every shopkeeper, and what they stock');
L.push('');
L.push('Generated by `tools/ff3-shop-catalog.mjs`. Verified against the running game');
L.push('by `tools/ff3-shop-probe.mjs --all` (names AND prices, 0 mismatches);');
L.push('pinned by `tools/check-ff3-shops.mjs`.');
L.push('');
L.push('This is the ROM\'s own table, not ff3mmo\'s `src/data/shops.js` — that one is');
L.push('the game\'s own design and is deliberately different.');
L.push('');
L.push('A shop is a shopkeeper NPC. `tools/ff3-shop-sweep.mjs` established which ids');
L.push('open one by patching a shopkeeper\'s id and talking to all 256.');
L.push('');
L.push('| table | where | per entry |');
L.push('|---|---|---|');
L.push(`| shop record ptr | bank 44 \`$8200\`, file \`0x${S.SHOP_PTR_TABLE.toString(16)}\` | 2 bytes LE, by NPC id |`);
L.push(`| item price | bank 16 \`$9E00\`, file \`0x${S.PRICE_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push(`| item name ptr | bank 24 \`$8800\`, file \`0x${S.NAME_PTR_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push('');
L.push(`A record is \`[kind][up to ${S.SHOP_ITEMS_MAX} item ids]\`, ended early by a \`00\`.`);
L.push('Kind bytes: ' + Object.entries(S.KINDS).map(([k, v]) => `\`${k}\` ${v}`).join(', ') + '.');
L.push('');
L.push('⛔ 232, 239, 244 and 250 have well-formed records and open **nothing**, so the');
L.push('shop id list is measured rather than derived from "has a record".');
L.push('');
L.push('| NPC id | kind | record | stock |');
L.push('|---|---|---|---|');
for (const s of S.allShops(rom, glyph)) {
  const stock = s.items.map(i =>
    `${i.name} \`0x${i.id.toString(16).padStart(2, '0')}\` — ${i.price} G`).join('<br>');
  L.push(`| ${s.npcId} | ${s.kind} | \`0x${s.offset.toString(16)}\` | ${stock} |`);
}
L.push('');
const md = L.join('\n');
if (process.argv.includes('--stdout')) process.stdout.write(md);
else { fs.writeFileSync(OUT, md); console.log(`wrote ${OUT} (${S.SHOP_NPC_IDS.length} shops)`); }
