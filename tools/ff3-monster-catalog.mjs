#!/usr/bin/env node
// ff3-monster-catalog.mjs — FF3's bestiary, to docs/FF3-MONSTERS.md.
//
// Pure ROM read through `lib/ff3-monsters.mjs`, whose addresses were mapped by
// tracing a real Goblin encounter and whose HP / attack / defence / evade fields
// are pinned by `check-ff3-monsters.mjs`.
//
//   node tools/ff3-monster-catalog.mjs
//
// ⛔ Only the columns below are MEASURED. The rest of the 16-byte record is
// inherited from Data Crystal and is deliberately not tabulated here — printing
// it beside measured columns would launder a citation into a measurement.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { initTextDecoder, getMonsterName } from '../src/text-decoder.js';
import * as M3 from './lib/ff3-monsters.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROMP = path.join(HERE, '..', 'FF3-English.nes');
const OUT = path.join(HERE, '..', 'docs', 'FF3-MONSTERS.md');
const rom = new Uint8Array(fs.readFileSync(ROMP));
initTextDecoder(Buffer.from(rom));

const MONSTER_COUNT = 232;

function nesText(bytes) {
  let s = '';
  for (const b of bytes) {
    if (b >= 0xCA && b <= 0xE3) s += String.fromCharCode(b - 0xCA + 97);
    else if (b >= 0x8A && b <= 0xA3) s += String.fromCharCode(b - 0x8A + 65);
    else if (b >= 0x80 && b <= 0x89) s += String.fromCharCode(b - 0x80 + 48);
    else if (b === 0xFF) s += ' ';
  }
  return s.trim();
}
const nameOf = (id) => { try { return nesText(getMonsterName(id)); } catch { return `mon${id}`; } };

const hex = (n, w = 2) => `0x${n.toString(16).toUpperCase().padStart(w, '0')}`;
const rows = [];
for (let id = 0; id < MONSTER_COUNT; id++) {
  const name = nameOf(id);
  if (!name) continue;
  rows.push({
    id, name,
    hp: M3.monsterHP(rom, id),
    atk: M3.monsterAttack(rom, id),
    def: M3.monsterDefence(rom, id),
    evd: M3.monsterEvade(rom, id),
    gil: M3.monsterGil(rom, id),
  });
}

const L = [];
L.push('# FF3 monsters — the measured fields');
L.push('');
L.push('Generated by `tools/ff3-monster-catalog.mjs`. Pinned by');
L.push('`tools/check-ff3-monsters.mjs`, which fights a real Goblin for every claim.');
L.push('');
L.push('`tools/gen-monsters-js.js` already built `src/data/monsters.js` from these');
L.push('tables, but its header credited "Data Crystal ROM map" — a secondary source.');
L.push('This project\'s rule is that the ROM beats a wiki, so the layout was put in');
L.push('front of the running game the way FF1\'s and FF2\'s were.');
L.push('');
L.push('## The tables');
L.push('');
L.push('| table | file offset | shape |');
L.push('|---|---|---|');
L.push(`| monster properties | \`0x${M3.MONSTER_PROPS.toString(16)}\` | ${M3.PROPS_STRIDE} bytes per bestiary id |`);
L.push(`| stat entries | \`0x${M3.STAT_TABLE.toString(16)}\` | ${M3.STAT_ENTRY} bytes per entry, indexed BY the record |`);
L.push(`| gil | \`0x${M3.MONSTER_GIL.toString(16)}\` | 2 bytes LE per id |`);
L.push('');
L.push('Tracing an actual encounter and mapping every cartridge read back to a file');
L.push('offset shows the game reading exactly these addresses. That is a measurement,');
L.push('not a citation.');
L.push('');
L.push('## What was measured');
L.push('');
L.push('**HP** is properties `+1`/`+2`. Patching it to 300 and then 400 puts exactly');
L.push('those values into the enemy block in RAM.');
L.push('');
L.push(`**ATTACK** is byte ${M3.STAT_ATK_OFF} of the stat entry that properties ` +
       `\`+${M3.VERIFIED_FIELDS.atkHitIdx}\` points at. Patching it to 0 and then 255`);
L.push('moves the damage the party TAKES from 34 to 118.');
L.push('');
L.push(`**DEFENCE** (byte ${M3.STAT_DEF_OFF}) and **EVADE** (byte ${M3.STAT_EVADE_OFF}) ` +
       `share the entry properties \`+${M3.VERIFIED_FIELDS.defEvdIdx}\` points at.`);
L.push('Both cut the damage the party deals, so "damage fell" pins neither. They');
L.push('separate on the same signature FF1\'s do — **evasion drives damage to ZERO,');
L.push('defence FLOORS it above zero** (Goblin, entry `[0,10,1]`):');
L.push('');
L.push('```');
L.push('byte 0 = 0/32/64/128/192/255  ->  99  0  0  0  0  0     floor ZERO');
L.push('byte 2 = 0/32/64/128/192/255  -> 111 12 12 12 12 12     floor TWELVE');
L.push('```');
L.push('');
L.push('and the battle text settles it outright. At byte 0 = 255 the screen prints');
L.push('**"Miss" ×26**, a word that appears nowhere at baseline or with defence maxed.');
L.push('At byte 2 = 255 the hit counts are identical to baseline (`1xHit ×28,');
L.push('`2xHit ×12`, `3xHit ×2`) and only the damage collapses. Byte 0 makes the party');
L.push('miss; byte 2 lets them land and soaks it.');
L.push('');
L.push('## ⛔ What was retracted');
L.push('');
L.push('`$7678` **is not the monster\'s current HP.** It is a copy HP is loaded into');
L.push('that never moves again. An earlier pass measured damage there, read "0 dealt"');
L.push('every time, and concluded the party simply could not hurt a Goblin — so');
L.push('defence and evade were reported as unverifiable. Patching HP to 500 and');
L.push('scanning every address holding it:');
L.push('');
L.push('```');
L.push('$7678: 500 -> 500     $76B8: 500 -> 485   <-- the only one that moves');
L.push('$767A: 500 -> 500     $76BA: 500 -> 500');
L.push('```');
L.push('');
L.push(`Current HP is \`$${M3.ENEMY_CUR_HP.toString(16).toUpperCase()}\`; ` +
       `\`$${M3.ENEMY_MAX_HP.toString(16).toUpperCase()}\` is the max beside it.`);
L.push('The lesson: an address that merely **holds** the right value at battle start');
L.push('has not been shown to be the live one — make it move first.');
L.push('');
L.push('Byte 1 of the defence entry (Goblin\'s natural 10) does nothing measurable —');
L.push('0 and 255 both leave the damage at exactly 99, on a measurement sensitive');
L.push('enough to catch both of its neighbours. It is left unnamed rather than guessed.');
L.push('');
L.push('Everything else in the 16-byte record (level, spAtkRate, weakness, spirit,');
L.push('atkElem, statusOnAtk, elemResist, statusResist, spAtkIdx) is **inherited from');
L.push('Data Crystal, not measured.** Do not cite it as verified.');
L.push('');
L.push(`## The bestiary — ${rows.length} monsters`);
L.push('');
L.push('| id | name | HP | attack | defence | evade | gil |');
L.push('|---|---|---|---|---|---|---|');
for (const r of rows) {
  L.push(`| \`${hex(r.id)}\` | ${r.name} | ${r.hp} | ${r.atk} | ${r.def} | ${r.evd} | ${r.gil} |`);
}
L.push('');

fs.writeFileSync(OUT, L.join('\n'));
console.log(`wrote docs/FF3-MONSTERS.md (${rows.length} monsters)`);
