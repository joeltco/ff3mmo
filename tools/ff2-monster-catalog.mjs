#!/usr/bin/env node
// ff2-monster-catalog.mjs — FF2's monster names, to docs/FF2-MONSTERS.md.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as F2 from './lib/ff2-text.mjs';
import * as MN from './lib/ff2-monsters.mjs';
import { romaji } from './lib/romaji.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF2-MONSTERS.md');
const rom = new Uint8Array(fs.readFileSync(process.env.FF2_ROM || '/home/joeltco/roms/ff2-jp.nes'));

const list = MN.allMonsters(rom, F2.glyph);
const L = [];
L.push('# FF2 monsters — the name table');
L.push('');
L.push('Generated by `tools/ff2-monster-catalog.mjs`.');
L.push('');
L.push(`Table: bank 5, file \`0x${MN.NAME_PTR_TABLE.toString(16)}\`, 2 bytes LE per id, pointing at a`);
L.push('`00`-terminated string. **128 entries**, Leg Eater through the Emperor.');
L.push('');
L.push('⛔ **Verification.** This table is not pinned to an instruction — FF2\'s battle');
L.push('code has not been traced. It is confirmed a different way: object types 73-76');
L.push('are monster GUARDS that name their monster in dialogue and then start the');
L.push('fight (found by `ff2-type-sweep.mjs`). Talking to each and reading the battle');
L.push('screen gives four confirmations spread across the table, each agreeing with');
L.push('what the guard said it was guarding:');
L.push('');
L.push('| guard type | index | name |');
L.push('|---|---|---|');
for (const c of MN.CONFIRMED) L.push(`| ${c.type} | ${c.id} | ${c.name} |`);
L.push('');
L.push('| id | name | romaji | | id | name | romaji |');
L.push('|---|---|---|---|---|---|---|');
const h = Math.ceil(list.length / 2);
for (let i = 0; i < h; i++) {
  const a = list[i], b = list[i + h];
  L.push(`| ${a.id} | ${a.name} | ${romaji(a.name)} | | ${b ? b.id : ''} | ${b ? b.name : ''} | ${b ? romaji(b.name) : ''} |`);
}
L.push('');
fs.writeFileSync(OUT, L.join('\n'));
console.log(`wrote ${OUT} (${list.length} names)`);
