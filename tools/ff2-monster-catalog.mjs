#!/usr/bin/env node
// ff2-monster-catalog.mjs — FF2's monster names, to docs/FF2-MONSTERS.md.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as F2 from './lib/ff2-text.mjs';
import * as MN from './lib/ff2-monsters.mjs';
import { romaji } from './lib/romaji.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF2-MONSTERS.md');
const rom = new Uint8Array(fs.readFileSync(process.env.FF2_ROM || '/home/joeltco/roms/ff2-jp.nes'));

const list = MN.allMonsters(rom, F2.glyph);
const L = [];
L.push('# FF2 monsters — the name table');
L.push('');
L.push('Generated by `tools/ff2-monster-catalog.mjs`.');
L.push('');
L.push(`Table: bank 5, file \`0x${MN.NAME_PTR_TABLE.toString(16)}\`, 2 bytes LE per id, pointing at a`);
L.push('`00`-terminated string. **128 entries**, Leg Eater through the Emperor.');
L.push('');
L.push('⛔ **Verification.** This table is not pinned to an instruction — FF2\'s battle');
L.push('code has not been traced. It is confirmed a different way: object types 73-76');
L.push('are monster GUARDS that name their monster in dialogue and then start the');
L.push('fight (found by `ff2-type-sweep.mjs`). Talking to each and reading the battle');
L.push('screen gives four confirmations spread across the table, each agreeing with');
L.push('what the guard said it was guarding:');
L.push('');
L.push('| guard type | index | name |');
L.push('|---|---|---|');
for (const c of MN.CONFIRMED) L.push(`| ${c.type} | ${c.id} | ${c.name} |`);
L.push('');
L.push('## Stats');
L.push('');
L.push('⭐ **HP is not stored as a number anywhere.** Record byte 0 is an INDEX into');
L.push('a shared 16-bit value pool — searching the whole ROM at every stride 1-32 for');
L.push('Adamantoise\'s 450 returns nothing, because the record only holds `0x0E`.');
L.push('Every later byte packs TWO 4-bit indexes resolved through 16-entry tables.');
L.push('');
L.push('```');
L.push('12/$9962  LDA $04 / ADC #$C3       ; record base $87C3 + monster*10');
L.push('12/$9972  ASL A / ADC #$C3 / #$8C  ; -> the VALUE POOL at $8CC3, idx*2');
L.push('12/$997E  LDA ($78),Y -> $4E,$52   ; ...that is HP');
L.push('12/$998D  LDY #$02, same pool      ; record byte 1 -> MP');
L.push('12/$99B4  JSR $FD07                ; later bytes: a NIBBLE split into');
L.push('12/$99B8  LDA $8D03,Y / $8D13,X    ; 16-entry tables');
L.push('12/$9A3C  CPX #$30                 ; 48 bytes per enemy in RAM, x8');
L.push('```');
L.push('');
L.push(`| table | where | per entry |`);
L.push('|---|---|---|');
L.push(`| stat record | bank 12 \`$87C4\`, file \`0x${MN.STAT_TABLE.toString(16)}\` | ${MN.STAT_STRIDE} bytes |`);
L.push(`| value pool | bank 12 \`$8CC3\`, file \`0x${MN.VALUE_POOL.toString(16)}\` | 2 bytes LE |`);
L.push('');
L.push('⛔ **Only HP is behaviourally proven** — the pool value matches the HP the');
L.push('battle loads, the RAM byte counts down when the monster is hit, and patching');
L.push('the index changes the HP that loads (`0x00` → 0, `0xFF` → 28282). MP is read');
L.push('from the same pool by the instruction after HP\'s, but was not separately');
L.push('tested. The nibble-packed bytes 2-9 measurably affect combat (zeroing byte 5');
L.push('tripled the damage the party dealt) but are **left unnamed rather than');
L.push('guessed at**.');
L.push('');
L.push('| id | name | romaji | HP | MP | record |');
L.push('|---|---|---|---|---|---|');
for (const m of list) {
  L.push(`| ${m.id} | ${m.name} | ${romaji(m.name)} | ${m.hp} | ${m.mp} | \`${m.stats.map(v => v.toString(16).padStart(2, '0')).join(' ')}\` |`);
}
L.push('');
fs.writeFileSync(OUT, L.join('\n'));
console.log(`wrote ${OUT} (${list.length} names)`);
