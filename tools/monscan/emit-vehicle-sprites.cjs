// emit-vehicle-sprites.cjs — capture the world-map VEHICLE sprites as DATA.
//
// FF3 is CHR-RAM: a vehicle's tiles are decompressed into pattern memory at run
// time, so there is no ROM offset to point `Sprite.gfxBase` at. The tiles must be
// captured off the PPU and shipped as bytes, the same way spell/monster art is.
//
// Boots aboard each vehicle on open ocean (world-harness) and records, per mode:
// the OAM layout, the 16-byte pattern for every tile used, and the sprite palette.
//
//   node tools/monscan/emit-vehicle-sprites.cjs src/data/vehicle-sprites-captured.js
const H=require('./world-harness.cjs');
const fs=require('fs');
(async()=>{
const romJ=new Uint8Array(fs.readFileSync('/home/joeltco/roms/ff3-jp.nes'));
const {loadWorldMap}=await import('../../src/world-map-loader.js');
const w=loadWorldMap(romJ,0);
const b1=(x,y)=>w.tileProps[w.tilemap[((y&127)*128)+(x&127)]&0x7F].byte1;
let ocean=null,land=null;
for(let y=6;y<120&&!ocean;y++)for(let x=6;x<120;x++){
  let ok=true; for(let d=0;d<=2;d++) if((b1(x+d,y)&0x0F)!==0b1011) ok=false;
  if(ok) ocean=[x,y];
}
for(let y=6;y<120&&!land;y++)for(let x=6;x<120;x++) if(!(b1(x,y)&1)&&!(b1(x,y)&0x80)) land=[x,y];
const out=new Map();
for(const veh of [0,1,2,3,4,5,6,7]){
  const site = veh===0 ? land : ocean;
  let nes; try{ nes=H.bootToWorldMap({worldX:site[0],worldY:site[1],vehicle:veh}); }
  catch(e){ console.log(`veh ${veh}: boot failed`); continue; }
  H.run(nes,50);
  const m=nes.nes.cpu.mem, ppu=nes.nes.ppu, oam=ppu.spriteMem;
  const mode=m[0x42];
  if(out.has(mode)) continue;                       // already captured this mode
  const patBase=(ppu.f_spPatternTable?1:0)*0x1000;
  const ents=[]; for(let i=0;i<256;i+=4) if(oam[i]<0xEF)
    ents.push({y:oam[i]+1,tile:oam[i+1],attr:oam[i+2],x:oam[i+3]});
  if(!ents.length) continue;
  const x0=Math.min(...ents.map(e=>e.x)), y0=Math.min(...ents.map(e=>e.y));
  const tiles=new Map();
  for(const e of ents) if(!tiles.has(e.tile))
    tiles.set(e.tile, Array.from(ppu.vramMem.slice(patBase+e.tile*16, patBase+e.tile*16+16)));
  const pal=Array.from({length:16},(_,i)=>ppu.vramMem[0x3F10+i]&0x3F);
  out.set(mode,{
    mode,
    layout: ents.map(e=>[e.tile, e.x-x0, e.y-y0, (e.attr&0x40)?1:0, (e.attr&0x80)?1:0, e.attr&3]),
    tiles: [...tiles].map(([id,bytes])=>[id,bytes]),
    pal,
  });
  console.log(`mode ${mode}: ${ents.length} sprites, ${tiles.size} distinct tiles`);
}
const hex=a=>'['+a.map(v=>'0x'+v.toString(16).padStart(2,'0')).join(',')+']';
let src=`// vehicle-sprites-captured.js — GENERATED by tools/monscan/emit-vehicle-sprites.cjs
//
// FF3 is CHR-RAM: vehicle tiles are decompressed into pattern memory at run time,
// so there is no ROM offset to point Sprite.gfxBase at — the bytes have to be
// captured off the PPU, exactly like spell-anim-captured.js.
//
// Keyed by MOVEMENT MODE (ps.vehicle): 0 on foot, 2 canoe afloat, 3 ship,
// 4-7 flying. \`layout\` entries are [tileId, dx, dy, hflip, vflip, palIdx];
// \`tiles\` is [tileId, 16 pattern bytes]; \`pal\` is the 16 sprite-palette indices.
//
// Captured aboard each craft on open ocean via world-harness.cjs. Do not hand-edit.

export const CAPTURED_VEHICLE_SPRITES = new Map([
`;
for(const [mode,v] of [...out].sort((a,b)=>a[0]-b[0])){
  src+=`  [${mode}, {\n    layout: [${v.layout.map(l=>'['+l.join(',')+']').join(', ')}],\n`;
  src+=`    tiles: [\n${v.tiles.map(([id,b])=>`      [0x${id.toString(16)}, new Uint8Array(${hex(b)})],`).join('\n')}\n    ],\n`;
  src+=`    pal: ${hex(v.pal)},\n  }],\n`;
}
src+=`]);\n`;
fs.writeFileSync(process.argv[2],src);
console.log('-> '+process.argv[2]+`  (${out.size} modes)`);
})();
