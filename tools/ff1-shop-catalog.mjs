#!/usr/bin/env node
// ff1-shop-catalog.mjs — render every FF1 shop to docs/FF1-SHOPS.md.
//
// Pure ROM read through `lib/ff1-shops.mjs` — no emulation. The emulator's job
// is `ff1-shop-probe.mjs --all`, which opens each shop and checks this against
// what the game actually draws.
//
//   node tools/ff1-shop-catalog.mjs           # writes docs/FF1-SHOPS.md
//   node tools/ff1-shop-catalog.mjs --stdout

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as F1 from './lib/ff1-text.mjs';
import * as S from './lib/ff1-shops.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF1-SHOPS.md');
const ROMP = process.env.FF1_ROM || '/home/joeltco/roms/ff1-usa.nes';
const rom = new Uint8Array(fs.readFileSync(ROMP));

const shops = S.allShops(rom, F1.glyph);
const L = [];
L.push('# FF1 shops — every id, what it stocks, what it charges');
L.push('');
L.push('Generated by `tools/ff1-shop-catalog.mjs`. Verified against the running');
L.push('game by `tools/ff1-shop-probe.mjs --all`; pinned by `tools/check-ff1-shops.mjs`.');
L.push('');
L.push('A tile\'s property byte 1 is the shop id (`$CEB0`), so this table is what');
L.push('any door in any town opens. See `tools/lib/ff1-shops.mjs` for the listings.');
L.push('');
L.push('| table | where | per entry |');
L.push('|---|---|---|');
L.push(`| shop kind | CPU \`$EBB5\`, file \`0x${S.KIND_TABLE.toString(16)}\` | 1 byte, \`& 0x07\` |`);
L.push(`| shop record ptr | CPU \`$8300\` bank 14, file \`0x${S.SHOP_PTR_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push(`| item price | CPU \`$BC00\` bank 13, file \`0x${S.PRICE_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push(`| item name ptr | CPU \`$B700\` bank 10, file \`0x${S.NAME_PTR_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push('');
L.push(`The record is at most ${S.RECORD_MAX} bytes and ends at the first \`00\`.`);
L.push('INN and CLINIC records are not item lists — they are a 16-bit price.');
L.push('');

for (const kind of S.KINDS) {
  const rows = shops.filter(s => s.kind === kind);
  if (!rows.length) continue;
  L.push(`## ${kind}`);
  L.push('');
  L.push('| id | record | stock |');
  L.push('|---|---|---|');
  for (const s of rows) {
    const raw = '`' + s.raw.map(v => v.toString(16).padStart(2, '0')).join(' ') + '`';
    let stock;
    if (s.unused) stock = '_(unused slot — points at the shared filler)_';
    else if (S.PRICE_KINDS.has(kind)) stock = `**${s.price} G**`;
    else stock = s.items.map(i =>
      `${i.name} \`0x${i.id.toString(16).padStart(2, '0')}\` — ${i.price} G`).join('<br>') || '_(empty)_';
    L.push(`| ${s.id} | ${raw} | ${stock} |`);
  }
  L.push('');
}

const used = shops.filter(s => !s.unused).length;
L.push(`---`);
L.push('');
L.push(`${used} shops in use out of ${shops.length} ids; ` +
       `${shops.length - used} are unused slots at the tail of each band.`);
L.push('');

const md = L.join('\n');
if (process.argv.includes('--stdout')) process.stdout.write(md);
else { fs.writeFileSync(OUT, md); console.log(`wrote ${OUT} (${used} shops in use)`); }
