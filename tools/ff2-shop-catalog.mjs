#!/usr/bin/env node
// ff2-shop-catalog.mjs — render every FF2 shop to docs/FF2-SHOPS.md.
//
// Pure ROM read through `lib/ff2-shops.mjs`. The emulator's job is
// `ff2-shop-probe.mjs --all`, which opens all 28 and compares.
//
//   node tools/ff2-shop-catalog.mjs
//   node tools/ff2-shop-catalog.mjs --stdout

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as F2 from './lib/ff2-text.mjs';
import * as S from './lib/ff2-shops.mjs';
import { romaji } from './lib/romaji.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF2-SHOPS.md');
const ROMP = process.env.FF2_ROM || '/home/joeltco/roms/ff2-jp.nes';
const rom = new Uint8Array(fs.readFileSync(ROMP));

const L = [];
L.push('# FF2 shops — every one of the 28, and what it stocks');
L.push('');
L.push('Generated by `tools/ff2-shop-catalog.mjs`. Verified against the running game');
L.push('by `tools/ff2-shop-probe.mjs --all` (names AND prices, 0 mismatches);');
L.push('pinned by `tools/check-ff2-shops.mjs`.');
L.push('');
L.push('A shop is an OBJECT TYPE, not a tile: talking to object type 192-219 opens');
L.push('one. `tools/ff2-type-sweep.mjs` established that by standing all 256 types');
L.push('next to the party. The four types after the shops are special:');
L.push('');
L.push('| type | what it is |');
L.push('|---|---|');
for (const [t, name] of Object.entries(S.SPECIAL_TYPES)) {
  L.push(`| ${Number(t)} (\`0x${Number(t).toString(16).toUpperCase()}\`) | ${name} |`);
}
L.push('');
L.push('| table | where | per entry |');
L.push('|---|---|---|');
L.push(`| shop record | CPU \`$860D\` bank 14, file \`0x${S.SHOP_TABLE.toString(16)}\` | ${S.SHOP_STRIDE} bytes = ${S.SHOP_ITEMS} x (item, price code) |`);
L.push(`| price by code | CPU \`$8000\` bank 14, file \`0x${S.PRICE_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push(`| item name ptr | CPU \`$8200\` bank 10, file \`0x${S.NAME_PTR_TABLE.toString(16)}\` | 2 bytes LE |`);
L.push('');
L.push('The second byte of an entry is a **price code**, not a price: the same code');
L.push('gives the same price for different items (`0xF2` is 500 G for both Axe and');
L.push('Mace), and it indexes the table above.');
L.push('');
L.push('| shop | type | record | stock |');
L.push('|---|---|---|---|');
for (const s of S.allShops(rom, F2.glyph)) {
  const raw = '`' + s.raw.map(v => v.toString(16).padStart(2, '0')).join(' ') + '`';
  const stock = s.items.map(i =>
    `${i.name} (${romaji(i.name)}) \`0x${i.id.toString(16).padStart(2, '0')}\` — ${i.price} G`).join('<br>');
  L.push(`| ${s.index} | ${s.objType} | ${raw} | ${stock} |`);
}
L.push('');

const md = L.join('\n');
if (process.argv.includes('--stdout')) process.stdout.write(md);
else { fs.writeFileSync(OUT, md); console.log(`wrote ${OUT} (${S.SHOP_COUNT} shops)`); }
