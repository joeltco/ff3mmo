#!/usr/bin/env node
// ff1-monster-catalog.mjs — FF1's monster names, to docs/FF1-MONSTERS.md.
//
// Pure ROM read through `lib/ff1-monsters.mjs`, whose table address is pinned to
// the instruction that reads it (`$FC83 LDA $94E0,X`) by `check-ff1-shops.mjs`.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as F1 from './lib/ff1-text.mjs';
import * as MN from './lib/ff1-monsters.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'docs', 'FF1-MONSTERS.md');
const rom = new Uint8Array(fs.readFileSync(process.env.FF1_ROM || '/home/joeltco/roms/ff1-usa.nes'));

const list = MN.allMonsters(rom, F1.glyph);
const L = [];
L.push('# FF1 monsters — the name table');
L.push('');
L.push('Generated by `tools/ff1-monster-catalog.mjs`.');
L.push('');
L.push('Found by teleporting the party to open overworld (`$27`/`$28` are pokeable),');
L.push('walking until an encounter fired, and watching what the battle read:');
L.push('');
L.push('```');
L.push('$FC77  LDA $6BE4,X          ; the monster id, out of battle RAM');
L.push('$FC7B  LDA #$0B / JSR $FE03 ; ...bank 11');
L.push('$FC83  LDA $94E0,X -> $94   ; the NAME POINTER, 2 bytes per id');
L.push('$FC94  LDY #$00 / LDA ($94),Y / BEQ   ; print until the 00');
L.push('```');
L.push('');
L.push(`Table: bank 11 \`$94E0\`, file \`0x${MN.NAME_PTR_TABLE.toString(16)}\`, 2 bytes LE per id.`);
L.push('');
L.push('⭐ **All 128 names have been made to appear in a real battle and read off');
L.push('the screen — 128/128** (`tools/ff1-monster-verify.mjs`). The way in was the');
L.push('formation record: byte 2 is the monster id, found by patching each of the 16');
L.push('bytes in turn and seeing which one changed the name the game drew.');
L.push('');
L.push(`Formations: bank 11 \`$8400\`, file \`0x${MN.FORMATION_TABLE.toString(16)}\`, ${MN.FORMATION_STRIDE} bytes each.  `);
L.push(`Stats: bank 12 \`$8520\`, file \`0x${MN.STAT_TABLE.toString(16)}\`, ${MN.STAT_STRIDE} bytes each.`);
L.push('');
L.push('Every field below was established by CHANGING that byte and watching the');
L.push('game behave differently — never by matching against a wiki:');
L.push('');
L.push('| bytes | field | how it was established |');
L.push('|---|---|---|');
L.push('| 0-1 | EXP | award = field / 2, linear over five values (6, 18, 438, 1337, 4242 → 3, 9, 219, 668, 2121 on the victory screen) |');
L.push('| 2-3 | GIL | award = field × 2, linear over five values (6, 18, 108, 999, 777 → 12, 36, 216, 1998, 1554) |');
L.push('| 4-5 | HP | RAM 13 is current HP: it counts down as the monster is hit, reaches 0, and RAM 17 flips to a dead flag |');
L.push('| 8 | evade | the damage the party lands falls to **zero** as it rises (0/32/128/255 → 32/19/1/0 over 120 rounds) |');
L.push('| 9 | defense | damage falls too but **floors above zero** (0/32/128/255 → 59/9/9/9) — that floor is what separates a reduction from a miss chance |');
L.push('| 12 | attack | zeroing it drops the damage the party TAKES from 35 to 1 |');
L.push('');
L.push('| 7 | special | a special-attack id, `0xFF` = none. **46 of 128** carry one, ids `0x00`-`0x2B` with no gaps, ending CHAOS `0x2A` and ASTOS `0x2B` |');
L.push('| 13 | crit | raising it makes the game print **"Critical hit!!"**; at 0 it never does. Natural range across all 128 is 0..70 |');
L.push('| 10 | hits | `$A761 LDA $6871 / LDX $6870 / JSR $AE09` — a multiply, clamped to a minimum of 1 |');
L.push('| 16, 18 | property masks | ANDed against two defender fields, `ORA / BEQ skip`, then **×40** damage |');
L.push('| 15 | status | `$A85F LDA $6873 / BEQ skip` gates a path that immediately ANDs with byte 18\'s mask |');
L.push('| 11 | (a second multiplier term) | `$A71F LDX $686F / JSR $AEDD`, the same routine the ×40 bonus uses |');
L.push('');
L.push('⭐ The MASK bytes are now **proven behaviourally**, by giving the party a');
L.push('weakness. The defender\'s fields sit at `$6800 + n*0x12`, `+0x0D` and `+0x0E`,');
L.push('and every party member\'s are `0x00` in a stock save — which is exactly why');
L.push('patching the monster alone had looked like it did nothing. Poke them and the');
L.push('AND fires. IMP\'s natural byte 16 is `0x04`:');
L.push('');
L.push('| party weakness | damage taken |');
L.push('|---|---|');
L.push('| `0x04` — the one matching bit | **24** |');
L.push('| `0xFB` — every bit except it | 12 |');
L.push('| `0x00` | 12 |');
L.push('| `0xFF` vs monster masks `0xFF` | **24** |');
L.push('| `0xFF` vs monster masks `0x00` | 12 |');
L.push('');
L.push('Only the specific bit matters, in both directions.');
L.push('');
L.push('⛔ Bytes 14, 17 and 19 are never read during a battle and nothing moved them.');
L.push('Byte 6 gates whether the monster attacks but was not isolated further. Those');
L.push('four are left **unnamed rather than guessed at**.');
L.push('');
L.push(`${list.length} monsters.`);
L.push('');
L.push('| id | name | HP | atk | def | evade | crit | special | exp | gil | raw record |');
L.push('|---|---|---|---|---|---|---|---|---|---|---|');
for (const m of list) {
  const v = (k) => MN.statValue(rom, m.id, k);
  const sp = v('special');
  L.push(`| ${m.id} | ${m.name} | ${v('hp')} | ${v('attack')} | ${v('defense')} | ${v('evade')} | ${v('crit')} | ${sp === MN.NO_SPECIAL ? '—' : '`0x' + sp.toString(16).padStart(2, '0') + '`'} | ${v('exp')} | ${v('gil')} | \`${m.stats.map(x => x.toString(16).padStart(2, '0')).join(' ')}\` |`);
}
L.push('');
fs.writeFileSync(OUT, L.join('\n'));
console.log(`wrote ${OUT} (${list.length} names)`);
