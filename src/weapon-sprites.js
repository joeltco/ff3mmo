/**
 * Build a raised/swung pair where each pose has its OWN tiles.
 *
 * _buildBladeCanvas reorders one tile set to make the swung pose, which works
 * for the original four weapons. The PPU-captured classes have genuinely
 * different artwork per pose (measured: distinct pixel patterns at the two
 * positions), so each is built from its own tiles.
 */
function _buildPosePair(raisedTiles, swungTiles, palette) {
  const quad = [[0, 0], [8, 0], [0, 8], [8, 8]];
  const make = (tiles) => {
    const c = document.createElement('canvas');
    c.width = 16; c.height = 16;
    const cctx = c.getContext('2d');
    tiles.forEach((t, i) => _blitTile(cctx, decodeTile(t, 0), palette, quad[i][0], quad[i][1]));
    return c;
  };
  return { raised: make(raisedTiles), swung: make(swungTiles) };
}

